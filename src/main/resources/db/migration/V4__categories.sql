-- Create product categories and relate each product to one category.
-- PostgreSQL / Supabase migration.

CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    description VARCHAR(2000),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- Hibernate may already have created this table without timestamp defaults.
-- Ensure direct SQL inserts receive valid timestamps as well.
ALTER TABLE categories
    ALTER COLUMN created_at SET DEFAULT CURRENT_TIMESTAMP,
    ALTER COLUMN updated_at SET DEFAULT CURRENT_TIMESTAMP;

ALTER TABLE products
    ADD COLUMN IF NOT EXISTS category_id BIGINT;

-- Recreate the constraint because V3 may already have added it without an
-- ON DELETE action. Deleting a category will safely unassign its products.
ALTER TABLE products
    DROP CONSTRAINT IF EXISTS fk_products_category;

ALTER TABLE products
    ADD CONSTRAINT fk_products_category
    FOREIGN KEY (category_id)
    REFERENCES categories(id)
    ON DELETE SET NULL;

-- Remove any duplicate category foreign key previously generated by Hibernate.
DO $$
DECLARE
    duplicate_constraint RECORD;
BEGIN
    FOR duplicate_constraint IN
        SELECT conname
        FROM pg_constraint
        WHERE conrelid = 'products'::regclass
          AND contype = 'f'
          AND conname <> 'fk_products_category'
          AND pg_get_constraintdef(oid) LIKE 'FOREIGN KEY (category_id)%'
    LOOP
        EXECUTE FORMAT(
            'ALTER TABLE products DROP CONSTRAINT %I',
            duplicate_constraint.conname
        );
    END LOOP;
END
$$;

CREATE INDEX IF NOT EXISTS idx_products_category_id
    ON products(category_id);

-- Preserve and normalize category data stored previously in products.category.
-- The guard keeps this script safe to rerun after the old column is removed.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'products'
          AND column_name = 'category'
    ) THEN
        INSERT INTO categories (name, created_at, updated_at)
        SELECT DISTINCT BTRIM(p.category), CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
        FROM products p
        WHERE NULLIF(BTRIM(p.category), '') IS NOT NULL
          AND NOT EXISTS (
              SELECT 1
              FROM categories c
              WHERE c.name = BTRIM(p.category)
          );

        UPDATE products p
        SET category_id = c.id
        FROM categories c
        WHERE p.category_id IS NULL
          AND c.name = BTRIM(p.category);
    END IF;
END
$$;

-- category_id is now the single source of truth.
ALTER TABLE products
    DROP COLUMN IF EXISTS category;



