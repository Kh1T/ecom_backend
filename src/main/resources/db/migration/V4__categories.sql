-- Create product categories and relate each product to one category.
-- PostgreSQL / Supabase migration.

CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    description VARCHAR(2000),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

ALTER TABLE products
    ADD COLUMN IF NOT EXISTS category_id BIGINT;

-- Add the foreign key only when it does not already exist (for example, if V3
-- has already created it).
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_products_category'
          AND conrelid = 'products'::regclass
    ) THEN
        ALTER TABLE products
            ADD CONSTRAINT fk_products_category
            FOREIGN KEY (category_id)
            REFERENCES categories(id)
            ON DELETE SET NULL;
    END IF;
END
$$;

CREATE INDEX IF NOT EXISTS idx_products_category_id
    ON products(category_id);

-- Preserve and normalize category data stored previously in products.category.
INSERT INTO categories (name)
SELECT DISTINCT BTRIM(p.category)
FROM products p
WHERE NULLIF(BTRIM(p.category), '') IS NOT NULL
  AND NOT EXISTS (
      SELECT 1
      FROM categories c
      WHERE c.name = BTRIM(p.category)
  );

UPDATE products p
SET category_id = c.id
FROM categories c
WHERE p.category_id IS NULL
  AND c.name = BTRIM(p.category);
